SELECT C.RFC, CU.NUM_CUENTA, CU.SALDO, T.NUM_TARJETA, T.FECHA_VEN, TT.DESCRIPCION
FROM CLIENTES C INNER JOIN CUENTAS CU --
ON C.CLIENTE_ID = CU.CLIENTE_ID -- ON SOBRE QUE COLUMNA SE VAN A SINCRONIZAR
INNER JOIN TARJETAS T
ON CU.CUENTA_ID = T.CUENTA_ID
INNER JOIN TIPO_TARJETA TT
ON T.TIPO_TARJETA_ID = TT.TIPO_T_ID AND C.RFC LIKE 'C%' ORDER BY CU.SALDO; --O T.FECHA_VEN 


