-- TABLA: COMPUESTA DE FILAS Y COLUMNAS
-- TUPLA:FILA O REGISTRO INDIVIDUAL
-- LLAVE PRIMARIA: NO DEBE REPETIRSE, SIRVE PARA IDENTIFICAR TUPLAS INDIVIDUALES
-- LLAVE FORANEA: RELACIONARSE 2 FILAS
-- TIPOS DE DATOS: NUMERICOS, CADENAS TEXTO, FECHA-HORA, BOOLEAN
-- NUMBER, NUMBER (6,2), DECIMAL, CHAR, VARCHAR, VARCHAR2, NVARCHAR2, DATE , TIMESTAMP

-- USUARIO: NOMBRE | AP_P | AP_M | FECHA_NAC | CURP | DOMICILIO
-- NUMEROS : NUM_TEL | TIPO 
-- COMPAÑIAS : NOMBRE

CREATE TABLE USUARIOS (
USER_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
NOMBRE VARCHAR2(25),
AP_P VARCHAR2(15),
AP_M VARCHAR2(15),
FECHA_NAC DATE,
CURP CHAR(18),
DOMICILIO VARCHAR2(50),
SEXO CHAR(1)
);


CREATE TABLE NUMEROS(
NUM_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
NUMERO CHAR(10),
TIPO VARCHAR2(10) -- MODIFICAR DESPUES
);

CREATE TABLE COMPAÑIAS(
COMP_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
NOMBRE VARCHAR2(15)
);


CREATE TABLE NUM_COMP(
ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
COMP_ID NUMBER,
NUMB_ID NUMBER
);

