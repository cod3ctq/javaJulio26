--TIPO_TARJETA TT
SELECT C.RFC, CU.NUM_CUENTA, CU.SALDO, T.NUM_TARJETA, T.FECHA_VEN, TT.DESCRIPCION
FROM CLIENTES C INNER JOIN CUENTAS CU
ON C.CLIENTE_ID = CU.CLIENTE_ID --SOBRE QUE COLUMNA SE SINCRONIZA
INNER JOIN TARJETAS T
ON CU.CUENTA_ID = T.CUENTA_ID
INNER JOIN TIPO_TARJETA TT
ON T.TIPO_TARJETA_ID = TT.TIPO_T_ID 
WHERE T.FECHA_VEN > TO_DATE ('31-12-2026', 'DD-MM-YYYY')
AND C.RFC LIKE 'C%'
ORDER BY T.FECHA_VEN;

