-- TABLA: COMPUESTA DE FILAS Y COLUMNAS
-- TUPLA: FILA O REGISTRO INDIVIDUAL
-- LLAVE PRIMARIA: NO DEBE REPETIRSE, SIRVE PARA IDENTIFICAR TABLAS INDIVIDUALES
-- LLAVE FORANEA: RELACIONA 2 FILAS
-- TIPOS DE DATOS: NUMERICOS, CADENAS DE TEXTO, FECHA-HORA, BOOLEAN
-- NUMBER, NUMBER(5 ENTERO,2 DOS DECIMAL) 999.99, DECIMAL, CHAR, VARCHAR, VARCHAR2, NVARCHAR2,DATE, TIMESTAMP

-- INTEGRIDAD REFERENCIAL, TRANSACCIONES

-- USUARIO : NOMBRE|AP_P|AP_M|FECHA_NAC|CURP|DOMICILIO
-- NUMEROS : NUM_TEL|TIPO
-- COMPAÑIAS : NOMBRE

CREATE TABLE USUARIOS(
USER_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
NOMBRE VARCHAR2(25),
AP_P VARCHAR2(15),
AP_M VARCHAR2(15),
FECHA_NAC DATE,
CURP CHAR(18),
DOMICILIO VARCHAR2(50),
SEXO CHAR(1) -- 
);
