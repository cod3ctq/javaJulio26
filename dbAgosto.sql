-- TABLA : COMPUESTA DE FILAS Y COLUMNAS
-- TUPLA : FILA O REGISTRO INDIVIDUAL
-- LLAVE PRIMARIA : IDENTIFICADOR, NO DEBE REPETIRSE, SIRVE PARA INDENTIFICAR TUPLAS INDIVIDUALES
-- LLAVE FORANEA : RELACIONAR 2> FILAS
-- NUMBER, NUMBER (5,2) -> 999.99(5 NUMEROS EN TOTAL Y 2 DECIMALES), DECIMAL, CHAR, VARCHAR, VARCHAR2, NVARCHAR2
-- DATE, TIMESTAMP

-- TIPOS DE DATOS
--INTEGRIDAD REFERENCIAL, TRANSACCIONES

-- USUARIO : NOMBRE|AP_P|AP_M|FECHA_NAC|CURP|DOMICILIO 
-- NUMEROS : NUM_TEL|TIPO
-- COMPANIA : NOMBRE

CREATE TABLE USUARIOS(
    USER_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    NOMBRE VARCHAR2(25),
    AP_P VARCHAR2(15),
    AP_M VARCHAR2(15),
    FECHA_NAC DATE,
    CURP CHAR(18),
    DOMICILIO VARCHAR2(50),
    SEXO CHAR(1)
);
-- VER LA ESTRUCTURA ACTUAL DE LA TABLA
DESCRIBE USUARIOS;
-- AGREGAR UNA COMLUMNA A UNA TABLA EXISTENTE
ALTER TABLE USUARIOS ADD SEXO CHAR(1);
-- CAMBIAR EL NOMBRE DE UNA COLUMNA
ALTER TABLE USUARIOS RENAME COLUMN DOMICILIO TO DIRECCION;
-- CAMBIAR EL TIPO DE DATO DE UNA COLUMNA
ALTER TABLE USUARIOS MODIFY SEXO VARCHAR2(10);
-- ELIMINAR UNA COLUMNA
ALTER TABLE USUARIOS DROP COLUMN DIRECCION;

CREATE TABLE NUMEROS (
    NUM_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
