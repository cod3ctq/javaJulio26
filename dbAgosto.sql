-- TABLA, TUPLA, LLAVE PRIMARIA, LLAVE FORANEA
-- TIPOS DE DATOS: NUMERICOS, CADENAS DE TEXTO, FECHA-HORA
-- NUMBER, NUMBER (5,2) 543.21, DECIMAL
-- CHAR, VARCHAR, VARCHAR2, NVARCHAR2
-- DATE, TIMESTAMP

-- INTEGRIDAD PREFERENCIAL, TRANSACCIONES
--------------------------------------------------------------------------------

-- BASE DE DATOS REGISTRO TELEFONICO

-- USUARIO: NOMBRE | AP_P | AP_M | FECHA_NAC | CURP | DOMICILIO
-- NUMEROS: NUM_TEL | TIPO
-- COMPAÑIAS: NOMBRE

CREATE TABLE USUARIOS( --CREAR UNA TABLA
--NOM COLUMNA | TIPO DE DATO QUE TENDRA | INDICA QUE VA A AUTOGENERAR LOS ID Y NO SE PUEDE REPETIR
USER_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY, -- PRIMER COLUMNA
NOMBRE VARCHAR2(25), --LAS COMAS SEPARAN COLUMNAS
AP_P VARCHAR2(15),
AP_M VARCHAR2(15),
FECHA_NAC DATE,
CURP CHAR(18),
DOMICILIO VARCHAR2(50)
);

CREATE TABLE NUMEROS(
NUM_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
NUMERO CHAR(10),
TIPO VARCHAR2(10) --MODIFICAR DESPUES
);

CREATE TABLE COMPAÑIAS(
NUM_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
NOMBRE VARCHAR2(15)
);

--TABLA PIVOTE, TABLA ALIMENTADA POR LAS LLAVES FORANEAS DE OTRAS TABLAS
CREATE TABLE NUM_COMP(
ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
COMP_ID NUMBER,
NUM_ID NUMBER
);


--VER ESTRUCTURA ACTUAL DE LA TABLA
DESCRIBE USUARIOS;
DESCRIBE LINEAS;
DESCRIBE COMPAÑIAS;
DESCRIBE NUM_COMP;

-- UNA VEZ EJECUTADO EL CODIGO YA QUEDA GUARDADO EN LA BASE. 
-- POR LO QUE NO SE PUEDE MODIFICAR EL CODIGO ORIGINAL PARA MODIFICAR LA BASE
-- SE TIENE QUE EJECUTAR NUEVO CODIGO PARA HACER MODIFICACIONES

--CAMBIAR EL NOMBRE DE UNA TABLA EXISTENE
ALTER TABLE NUMEROS RENAME TO LINEAS;

-- AGREGAR COLUMNA A UNA TABLA EXISTENE
--COMANDO | NOMBRE DE LA TABLA | ACCION | NOMBRE DE COLUMNA | TIPO DATO
ALTER TABLE USUARIOS ADD SEXO CHAR(1);

-- CAMBIAR NOMBRE DE UNA COLUMNA
--COMANDO | TABLA | ACCION | NOMBRE NUEVO | TO | NOMBRE NUEVO
ALTER TABLE USUARIOS RENAME COLUMN DOMICILIO TO DIRECCION;

-- CAMBIAR TIPO DE DATO DE UNA COLUMNA
ALTER TABLE USUARIOS MODIFY SEXO VARCHAR2(10);

-- ELIMINAR UNA COLUMNA
ALTER TABLE USUARIOS DROP COLUMN DIRECCION;



ALTER TABLE NUMEROS ADD USR_ID NUMBER;

--LLAVE FORANEA (FK)
--PARA NOMBRAR EL CONSTRAINT ES RECOMENDABLE HACERLO COMO: 
--LO QUE ES | NOMBRE DE LA TABLA DONDE SE INSTALA | COLUMNA A LA QUE SE APLICA
ALTER TABLE NUMEROS ADD CONSTRAINT FK_NUMEROS_USR_ID
FOREIGN KEY (USR_ID) --COLUMNA QUE RECIBE LA REGLA
REFERENCES USUARIOS(USER_ID); --DE DONDE VIENE EL DATO

--REGLAS PARA RELACIONAR IDS EN TABLA PIVOTE
ALTER TABLE NUM_COMP ADD CONSTRAINT FK_NUM_COMP_COMP_ID
FOREIGN KEY (COMP_ID)
REFERENCES COMPAÑIAS(NUM_ID);

ALTER TABLE NUM_COMP ADD CONSTRAINT FK_NUM_COMP_NUM_ID
FOREIGN KEY (NUM_ID)
REFERENCES NUMEROS(NUM_ID);

--UNIQUE(UQ) Y CHECK (CHK)
--                                  REGLA|TABLA|COLUMNA
ALTER TABLE USUARIOS ADD CONSTRAINT UQ_USUARIOS_CURP
UNIQUE (CURP);

--CUANDO LOS POSIBLES VALORES DE UNA COLUMNA NO VAYAN A CAMBIAR NUNCA O
--O SOLAMENTE EN UNA SITUACION EXTRAORDINARIA, PUEDEN ESTABLECERSE 'EN FIRME'
--USANDO CONSTRAINT CHECK
ALTER TABLE USUARIOS ADD CONSTRAINT CHK_USUARIOS_SEXO
CHECK (SEXO IN ('MASCULINO', 'FEMENINO'));

--EN ESTE CASO, ESTOS DATOS AUNQUE SE MANEJARON CON UN CONSTRAINT CHECK
--ES MUCHO MAS PROBABLE QUE EN ALGUN MOMENTO REQUIERAN ALGUNA MODIFICACION
--(AGREGAR/ELIMINAR TIPOS), ENTONCES TAMBIEN PODRIAN CONFIGURARSE MEDIANTE
--OTRA TABLA Y LLAVES FORANEAS
ALTER TABLE NUMEROS ADD CONSTRAINT CHK_NUMEROS_TIPO
CHECK (TIPO IN ('FISICO', 'VIRTUAL'));

--LIMITAR EL NUMERO DE VECES QUE PODEMOS RELACIONAR UNA LLAVE FORANEA DENTRO DE UNA TABLA
ALTER TABLE LINEAS ADD CONSTRAINT UQ_LINEAS_USR_ID
UNIQUE(USR_ID); --NO SE EJECUTÓ


