-- USUARIO: NOMBRE|AP_P|AP_M|FECHA_NAC|CURP|DOMICILIO
-- NUMEROS: NUM_TEL|TIPO
-- COMPAÑIAS: NOMBRE

-- CREACIÓN DE LA TABLA DE USUARIOS
CREATE TABLE USUARIOS(
USER_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
NOMBRE VARCHAR2(25),
AP_P VARCHAR2(15),
AP_M VARCHAR2 (15),
FECHA_NAC DATE,
CURP CHAR(18),
DOMICILIO VARCHAR2 (50),
SEXO CHAR(1) -- NO SE AGREGA A LA TABLA SI SE QUIERE INTRODUCIR DESPUÉS
);

--CREACION DE TABAL DE NÚMEROS
CREATE TABLE NUMEROS(
NUM_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
NUMERO CHAR(10),
TIPO VARCHAR2(10) --MODIFIAR DESPUÉS
);

-- CREACIÓN DE LA TABLA COMPAÑÍA
CREATE TABLE COMPAÑIAS(
COMP_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
NOMBRE VARCHAR2(15)
);

-- CREACIÓN DE LA TABLA PIVOTE COMPAÑIA-NÚMEROS
CREATE TABLE NUM_COMP(
ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
COMP_ID NUMBER,
NUM_ID NUMBER
);

--AGREGAR UNA COLUMNA A UNA TABLA EXISTENTE
ALTER TABLE USUARIOS ADD SEXO CHAR(1);

--CAMBIAR EL NOMBRE DE UNA COLUMNA
ALTER TABLE USUARIOS RENAME COLUMN DOMICILIO TO DIRECCION;

--CAMBIAR EL TIPO DE DATO DE UNA COLUMNA
ALTER TABLE USUARIOS MODIFY SEXO VARCHAR(10);

--ELIMINAR UNA COLUMNA
ALTER TABLE USUARIOS DROP COLUMN DIRECCION;

--CAMBIAR EL NOMBRE DE UNA TABLA EXISTENTE
ALTER TABLE NUMEROS RENAME TO LINEAS;

-- VER LA ESTRUCTURA ACTUAL DE LA TABLA
DESCRIBE NUMEROS;
ALTER TABLE NUMEROS ADD USR_ID NUMBER;

-- LLAVE FORÁNEA
ALTER TABLE NUMEROS ADD CONSTRAINT FK_NUMEROS_USR_ID
FOREIGN KEY(USR_ID) --COLUMNA QUE RECIBE LA REGLA
REFERENCES USUARIOS (USER_ID); -- DE DONDE VIENE EL DATO

-- LLAVE FORANEA DE NUMEROS A NUM_COMP
ALTER TABLE NUM_COMP ADD CONSTRAINT FK_NUM_COMP_NUM_ID
FOREIGN KEY(NUM_ID)
REFERENCES NUMEROS(NUM_ID);

--ELIMINAR UN CONSTRAINT
ALTER TABLE NUM_COMP DROP CONSTRAINT FK_NUMEROS_NUM_ID;

--LLAVER FOREANEA DE COMPAÑIAS A NUM_COMP
ALTER TABLE NUM_COMP ADD CONSTRAINT FK_NUM_COMP_COMP_ID
FOREIGN KEY(COMP_ID)
REFERENCES COMPAÑIAS(COMP_ID);

--ELIMINAR UN CONSTRAINT
ALTER TABLE NUM_COMP DROP CONSTRAINT FK_NUMEROS_COMP_ID;

-- CONSTRAINTS
ALTER TABLE USUARIOS ADD CONSTRAINT UQ_USUARIOS_CURP
UNIQUE(CURP);

-- CUANDO LOS POSIBLES VALORES DE UNA COLUMNA NO VAYAN A CAMBIAR NUNCA O
--SOLAMENTE EN UNA SITUACIÓN EXTRAORDINARIA, PUEDEN ESTABLECERSE 'EN FIRME'
--CON UN CONSTRAINT CHECK
ALTER TABLE USUARIOS ADD CONSTRAINT CHK_USUARIOS_SEXO
CHECK(SEXO IN('MASCULINO','FEMENINO'));

-- EN ESTE CASO, ESTOS DATOS AUNQUE SE MANEJARON CON UN CONSTRAINT CHECK
--ES MUCHO MÁS PROBABLE QUE EN ALGÚN MOMENTO REQUIERAN ALGUNA MODIFICACIÓN
--(AGREGAR/ELIMINAR TIPOS), ENTONCES TAMBIÉN PODRÍAN CONFIGURARSE MEDIANTE
--OTRA TABLA Y LLAVES FORÁNEAS
ALTER TABLE NUMEROS ADD CONSTRAINT CHK_NUMEROS_TIPO
CHECK(TIPO IN('FISICO','VIRTUAL'));

